package main

import "fmt"

func main() {

	// strings
	var firstName string = "Syahrul"
	var middleName = "Safarudin"
	lastName := "Hasan"
	fmt.Println(firstName, middleName, lastName)

	// integers
	var age int = 20
	fmt.Println(age)

	// boolean
	var isMarried bool = false
	fmt.Println(isMarried)

	// float
	var height float32 = 169.75
	fmt.Println(height)
}
